/*
 * The SQL that keeps change_log: four triggers per synced table. Standalone (no
 * imports) so scripts/sync-triggers.ts can load it with plain node.
 * A trigger can't call serverNow(), so `at` is SQLite's clock; phase 3's replay
 * corrects it for the entries it writes.
 */
const AT = "CAST(unixepoch('subsec') * 1000 AS INTEGER)";

function keyOf(row: 'NEW' | 'OLD', key: readonly string[]): string {
	if (key.length === 1) return `CAST(${row}.${key[0]} AS TEXT)`;
	return `json_array(${key.map((k) => `${row}.${k}`).join(', ')})`;
}

export function triggerSql(table: string, key: readonly string[]): string {
	const log = (row: 'NEW' | 'OLD', op: 'i' | 'u' | 'd') =>
		`INSERT INTO change_log (tbl, key, op, at) VALUES ('${table}', ${keyOf(row, key)}, '${op}', ${AT});`;
	return [
		`CREATE TRIGGER ${table}_log_i AFTER INSERT ON ${table} BEGIN\n  ${log('NEW', 'i')}\nEND;`,
		`CREATE TRIGGER ${table}_log_u AFTER UPDATE ON ${table} BEGIN\n  ${log('NEW', 'u')}\nEND;`,
		`CREATE TRIGGER ${table}_log_k AFTER UPDATE ON ${table} WHEN ${keyOf('OLD', key)} IS NOT ${keyOf('NEW', key)} BEGIN\n  ${log('OLD', 'd')}\nEND;`,
		`CREATE TRIGGER ${table}_log_d AFTER DELETE ON ${table} BEGIN\n  ${log('OLD', 'd')}\nEND;`
	].join('\n--> statement-breakpoint\n');
}

export const TRIGGERS_HEADER =
	'-- Generated by scripts/sync-triggers.ts from src/lib/sync/tables.ts. Do not edit by hand.\n';

export function triggersFile(synced: Readonly<Record<string, readonly string[]>>): string {
	return (
		TRIGGERS_HEADER +
		Object.entries(synced)
			.map(([t, k]) => triggerSql(t, k))
			.join('\n--> statement-breakpoint\n') +
		'\n'
	);
}
